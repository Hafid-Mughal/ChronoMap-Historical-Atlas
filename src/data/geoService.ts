const countriesGeoJson: any = topojson.feature(atlas, atlas.objects.countries);

/**
 * Projects [longitude, latitude] onto our 1000 x 520 cylindrical world canvas.
 * Crucially unwraps Northeast Russia (Chukotka Peninsula & Wrangel Island) and Fiji
 * across the 180° meridian so Russia's eastern corner is never broken off and
 * sits directly across the narrow Bering Strait from Alaska on every globe cycle.
 */
export function projectCoordinates(lon: number, lat: number): [number, number] {
  let adjLon = lon;

  // Unwrap Northeast Russia (Chukotka & Wrangel Island: lat >= 64.1°N, lon <= -169.5°W)
  // and Fiji (lat -20°S to -15°S, lon <= -178°W) across the 180° meridian
  if (lat >= 64.1 && lon <= -169.5) {
    adjLon = lon + 360;
  } else if (lat >= -20 && lat <= -15 && lon <= -178) {
    adjLon = lon + 360;
  }

  const x = ((adjLon + 180) / 360) * 1000;
  const clampedLat = Math.max(-85.5, Math.min(85.5, lat));
  const y = 260 - (clampedLat / 90) * 255;

  return [
    isNaN(x) ? 500 : x,
    isNaN(y) ? 260 : y
  ];
}

// Custom d3-geo stream transform using projectCoordinates (no oval antimeridian slicing)
export const mapProjection = geoTransform({
  point: function (lon: number, lat: number) {
    const [x, y] = projectCoordinates(lon, lat);
    this.stream.point(x, y);
  }
});

export const pathGenerator = geoPath(mapProjection);

/**
 * Converts a TopoJSON MultiLineString mesh into an SVG path string while suppressing
 * any artificial antimeridian wrap jumps (> 500px horizontal jump) or 180° seam cuts.
 */
export function generateCleanMeshPath(meshGeoJson: any): string {
  if (!meshGeoJson || !meshGeoJson.coordinates) return '';
  const parts: string[] = [];

  for (const line of meshGeoJson.coordinates) {
    if (!line || line.length < 2) continue;
    let started = false;
    let prevX = 0;
    let prevY = 0;

    for (let i = 0; i < line.length; i++) {
      const [lon, lat] = line[i];
      const [x, y] = projectCoordinates(lon, lat);

      if (!started) {
        parts.push(`M${x.toFixed(2)},${y.toFixed(2)}`);
        started = true;
      } else {
        // Skip artificial antimeridian jump lines (e.g., Antarctica closure across ±180°)
        if (Math.abs(x - prevX) > 450) {
          parts.push(`M${x.toFixed(2)},${y.toFixed(2)}`);
        } else {
          parts.push(`L${x.toFixed(2)},${y.toFixed(2)}`);
        }
      }
      prevX = x;
      prevY = y;
    }
  }

  return parts.join('');
}

