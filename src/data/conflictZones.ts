// Project all conflict zones using the real cartographic projection
export const CONFLICT_ZONES: ConflictZone[] = RAW_CONFLICT_ZONES.map((c) => ({
  ...c,
  center: projectCoordinates(c.geoCoords[0], c.geoCoords[1])
}));

/**
 * Returns all War Zones and Disputed Territories active in any given integer year (-3000 to 2026)
 */
export function getConflictsForEra(eraYear: number): ConflictZone[] {
  const matched = CONFLICT_ZONES.filter(
    (c) => eraYear >= c.startYear && eraYear <= c.endYear
  );

  if (matched.length > 0) {
    return matched;
  }

  // Fallback to closest historical conflicts if a year falls on a boundary
  return CONFLICT_ZONES.filter(
    (c) =>
      Math.abs(c.startYear - eraYear) <= 50 ||
      Math.abs(c.endYear - eraYear) <= 50
  );
}
